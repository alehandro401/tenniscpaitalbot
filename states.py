from aiogram.fsm.state import State, StatesGroup


class Flow(StatesGroup):
    """
    Состояния мастера записи. Нужны в первую очередь для того,
    чтобы игнорировать «протухшие» нажатия на старые инлайн-кнопки
    (например, если пользователь начал новый диалог, а потом
    случайно нажал кнопку из предыдущего сообщения).
    """
    sport = State()              # выбор вида спорта: теннис / бадминтон / пиклбол
    category = State()          # выбор: детская школа / взрослая школа / аренда корта (только теннис)
    lesson_type = State()       # выбор: групповые / персональные (для школ)
    subtype = State()           # подтип группы или персональных занятий
    level = State()             # уровень подготовки
    location = State()          # выбор локации (для школ)
    offer_format = State()      # выбор формата группы (если их несколько в локации)
    package = State()           # выбор тарифа/цены (там, где есть прайс-лист)
    contact = State()           # запрос номера телефона
    name = State()               # запрос имени
    consent = State()            # согласие с политикой/правилами/офертой
    date = State()               # выбор даты записи
    time = State()               # выбор времени записи
    rental_location = State()   # выбор локации (для аренды корта, теннис)
    rental_duration = State()   # длительность аренды (теннис)
    rental_date = State()        # выбор даты аренды (теннис)
    rental_time = State()        # выбор времени аренды (теннис)
    bp_location = State()        # выбор локации (бадминтон/пиклбол)
    equipment = State()          # выбор инвентаря (бадминтон/пиклбол)
    bp_date = State()             # выбор даты (бадминтон/пиклбол)
    bp_time = State()             # выбор времени (бадминтон/пиклбол)
    payment = State()           # ожидание подтверждения оплаты