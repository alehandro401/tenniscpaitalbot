def get_time_slots_for_window(
    weekday_start: str, weekday_end: str, weekend_start: str, weekend_end: str, date: dt.date
) -> list[str]:
    """Генерирует слоты по явно заданному расписанию (будни/выходные)."""
    is_weekend = date.weekday() >= 5  # 5=суббота, 6=воскресенье
    start, end = (weekend_start, weekend_end) if is_weekend else (weekday_start, weekday_end)
    return _time_slots(start, end)


