def get_hour_slots() -> list[str]:
    """Часовые слоты с 06:00 до 24:00 (последний слот начинается в 23:00)."""
    return [f"{h:02d}:00" for h in range(6, 24)]


def get_pickleball_hour_price(is_weekend: bool, time_str: str) -> int:
    if is_weekend:
        return 4000
    hour = int(time_str.split(":")[0])
    if 6 <= hour < 12:
        return 3500
    if 12 <= hour < 15:
        return 3000
    if 15 <= hour < 23:
        return 4000
    return 3500  # 23:00 — последний слот перед закрытием


def get_court_price(sport: str, is_weekend: bool, time_str: str) -> int:
    """Цена аренды корта за конкретный час (зависит от вида спорта/дня недели/времени)."""
    if sport == "badminton":
        return 3000  # флэт-цена, будни и выходные одинаково
    if sport == "pickleball":
        return get_pickleball_hour_price(is_weekend, time_str)
    return 0  # для тенниса цена считается отдельно, см. get_tennis_rental_price


