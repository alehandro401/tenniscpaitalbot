CANCEL_MIN_HOURS = 12  # отменить можно не позднее чем за столько часов до начала


def get_order_datetime(order) -> dt.datetime | None:
    """Собирает booking_date+booking_time заявки в единый datetime, либо None."""
    if not order.booking_date or not order.booking_time:
        return None
    return dt.datetime.combine(
        order.booking_date,
        dt.datetime.strptime(order.booking_time, "%H:%M").time(),
    )


def hours_until_order(order) -> float | None:
    order_dt = get_order_datetime(order)
    if order_dt is None:
        return None
    delta = order_dt - dt.datetime.utcnow()
    return delta.total_seconds() / 3600


