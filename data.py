BOOKING_DAYS_AHEAD = 14
SLOT_STEP_MINUTES = 60  # шаг сетки времени

RU_WEEKDAYS_SHORT = ["Пн", "Вт", "Ср", "Чт", "Пт", "Сб", "Вс"]


