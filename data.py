# ---------------------------------------------------------------------------
# Нормализация номера телефона. Правила:
#   11 цифр, начинается с 7  -> "+7XXXXXXXXXX"
#   11 цифр, начинается с 8  -> "8XXXXXXXXXX"
#   10 цифр (без кода страны) -> считаем российским номером -> "+7XXXXXXXXXX"
#   иначе -> невалидный номер (None)
# ---------------------------------------------------------------------------
def normalize_phone(raw: str) -> str | None:
    digits = re.sub(r"\D", "", raw)
    if len(digits) == 11:
        if digits[0] == "7":
            return "+7" + digits[1:]
        if digits[0] == "8":
            return "8" + digits[1:]
        return None
    if len(digits) == 10:
        return "+7" + digits
    return None


