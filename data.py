def _time_slots(start: str, end: str, step_minutes: int = SLOT_STEP_MINUTES) -> list[str]:
    fmt = "%H:%M"
    t_start = dt.datetime.strptime(start, fmt)
    t_end = dt.datetime.strptime(end, fmt)
    slots = []
    cur = t_start
    while cur + dt.timedelta(minutes=step_minutes) <= t_end:
        slots.append(cur.strftime(fmt))
        cur += dt.timedelta(minutes=step_minutes)
    return slots


def get_available_dates(days_ahead: int = BOOKING_DAYS_AHEAD) -> list[dt.date]:
    """Список дат на ближайшие days_ahead дней (все дни считаются рабочими)."""
    today = dt.date.today()
    return [today + dt.timedelta(days=i) for i in range(days_ahead)]


def format_date_label(d: dt.date) -> str:
    return f"{RU_WEEKDAYS_SHORT[d.weekday()]} {d.strftime('%d.%m')}"


def format_date_display(date_str: str | None) -> str | None:
    """Преобразует ISO-строку даты ('2026-09-22') в 'Вт, 22.09.2026' для показа клиенту."""
    if not date_str:
        return None
    try:
        d = dt.date.fromisoformat(date_str)
    except ValueError:
        return date_str
    return f"{RU_WEEKDAYS_SHORT[d.weekday()]}, {d.strftime('%d.%m.%Y')}"


